/* ── Logo renderers ──────────────────────────────────────── */
function SVGLogo({ iconKey, size = 18 }) {
  const icon = ICONS[iconKey]
  return (
    <svg width={size} height={size} viewBox={icon.viewBox} style={{ flexShrink: 0 }} aria-hidden="true">
      {icon.paths.map((p, i) => (
        <path key={i} d={p.d} fill={p.fill} />
      ))}
    </svg>
  )
}

function ImgLogo({ src, name, size = 18 }) {
  const [failed, setFailed] = useState(false)
  if (failed) {
    return (
      <span aria-hidden="true" style={{
        width: size, height: size, borderRadius: '4px',
        background: 'rgba(255,255,255,0.1)', border: '1px solid rgba(255,255,255,0.15)',
        display: 'inline-flex', alignItems: 'center', justifyContent: 'center',
        fontSize: size * 0.56, fontWeight: 700, color: 'rgba(255,255,255,0.55)',
        fontFamily: 'monospace', flexShrink: 0,
      }}>{name[0]}</span>
    )
  }
  return (
    <img src={src} width={size} height={size} alt="" aria-hidden="true"
      style={{ borderRadius: '3px', objectFit: 'contain', flexShrink: 0 }}
      onError={() => setFailed(true)}
    />
  )
}

/* ── Tool pill ───────────────────────────────────────────── */
function ToolPill({ tool }) {
  return (
    <span
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: '8px',
        padding: '8px 16px',
        borderRadius: '100px',
        background: 'rgba(255,255,255,0.05)',
        border: '1px solid rgba(255,255,255,0.09)',
        color: 'var(--text-2)',
        fontSize: '13px',
        fontWeight: 500,
        whiteSpace: 'nowrap',
        margin: '0 6px',
        transition: 'background 0.2s, border-color 0.2s',
        cursor: 'default',
      }}
      onMouseEnter={(e) => {
        e.currentTarget.style.background = 'rgba(255,255,255,0.09)'
        e.currentTarget.style.borderColor = 'rgba(255,255,255,0.16)'
      }}
      onMouseLeave={(e) => {
        e.currentTarget.style.background = 'rgba(255,255,255,0.05)'
        e.currentTarget.style.borderColor = 'rgba(255,255,255,0.09)'
      }}
    >
      {tool.img
        ? <ImgLogo src={tool.img} name={tool.name} />
        : <SVGLogo iconKey={tool.icon} />
      }
      {tool.name}
    </span>
  )
}

/* ── Marquee row ─────────────────────────────────────────── */
function MarqueeRow({ tools, className, style }) {
  const doubled = [...tools, ...tools, ...tools, ...tools]
  return (
    <div style={{ display: 'flex', overflow: 'hidden', ...style }}>
      <div className={className} style={{ display: 'flex', willChange: 'transform' }}>
        {doubled.map((tool, i) => (
          <ToolPill key={`${tool.name}-${i}`} tool={tool} />
        ))}
      </div>
    </div>
  )
}

